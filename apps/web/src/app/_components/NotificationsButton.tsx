// app/_components/NotificationsButton.tsx
"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { Bell, BellRing, CheckCheck } from "lucide-react";
import { createClient } from "@/lib/supabase/client";
import { useWebPushSubscription } from "@/lib/push/useWebPushSubscription";

interface Notification {
  id: string;
  title: string;
  body: string;
  is_read: boolean;
  created_at: string;
}

/**
 * Which feed this button reads. `notifications` rows belong to exactly one
 * audience — a customer or a vendor (0049_vendor_notifications.sql) — so
 * the audience decides both the column filtered on and the value.
 *
 * The vendor variant takes its id as a prop rather than deriving it here:
 * (vendor)/layout.tsx has already loaded the vendor through the DAL, and a
 * second client-side lookup would be a round trip to re-learn something the
 * server knew. RLS is what actually enforces the scoping either way — a
 * forged vendorId returns nothing, because reading a vendor's
 * notifications requires a matching vendor_staff row.
 */
type Audience = { audience: "customer" } | { audience: "vendor"; vendorId: string };

type NotificationsButtonProps = Audience & {
  /** Overrides for the two headers' different button treatments. */
  buttonClassName?: string;
  iconClassName?: string;
  /** Shown when the feed is empty — the two audiences expect different news. */
  emptyMessage?: string;
};

/** Same "honest, computed-from-real-data" relative time as orders/_components/timeAgo.ts,
 * duplicated locally rather than importing across route groups for one small helper. */
function timeAgo(isoDate: string): string {
  const ms = Date.now() - new Date(isoDate).getTime();
  const minutes = Math.max(0, Math.round(ms / 60_000));
  if (minutes < 1) return "Just now";
  if (minutes < 60) return `${minutes} min ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours} ${hours === 1 ? "hour" : "hours"} ago`;
  const days = Math.round(hours / 24);
  return `${days} ${days === 1 ? "day" : "days"} ago`;
}

/**
 * Real notifications, generated by DB triggers on order status changes
 * (0038 for customers, 0049 for vendors) — not the always-on decorative dot
 * both headers used to render regardless of whether anything had happened.
 * The dot only shows when `unreadCount > 0`, and a Realtime subscription
 * keeps it live without polling (the `notifications` table is in the
 * `supabase_realtime` publication).
 */
export function NotificationsButton(props: NotificationsButtonProps) {
  const {
    buttonClassName = "relative rounded-full p-2 transition-colors hover:bg-black/5",
    iconClassName = "size-5 text-[#5B403C] sm:size-4",
    emptyMessage = "Nothing here yet — updates about your orders will show up as they happen.",
  } = props;

  const [isOpen, setIsOpen] = useState(false);
  const [items, setItems] = useState<Notification[]>([]);
  const [unreadCount, setUnreadCount] = useState(0);
  const containerRef = useRef<HTMLDivElement>(null);
  const webPush = useWebPushSubscription();

  // Destructured so the callback below depends on primitives, not on the
  // props object — which is a fresh reference on every parent render and
  // would otherwise tear down and re-establish the realtime channel.
  const audience = props.audience;
  const vendorId = props.audience === "vendor" ? props.vendorId : null;

  const resolveScope = useCallback(
    async (
      supabase: ReturnType<typeof createClient>,
    ): Promise<{ column: "customer_id" | "vendor_id"; value: string } | null> => {
      if (audience === "vendor") {
        return vendorId ? { column: "vendor_id", value: vendorId } : null;
      }
      const {
        data: { user },
      } = await supabase.auth.getUser();
      return user ? { column: "customer_id", value: user.id } : null;
    },
    [audience, vendorId],
  );

  useEffect(() => {
    // `cancelled` guards against React StrictMode's dev-only double-invoke
    // of this effect: mount -> cleanup -> mount again, synchronously. The
    // first mount's cleanup calls removeChannel(), but that's genuinely
    // async (it awaits an unsubscribe round trip before the channel is torn
    // down - see @supabase/realtime-js's RealtimeClient.removeChannel()), so
    // it hasn't finished by the time the second mount runs. supabase.channel()
    // dedupes by topic and would hand back that still-joined channel, and
    // calling .on() on an already-subscribed channel is exactly what threw
    // "cannot add postgres_changes callbacks ... after subscribe()". Awaiting
    // the removal of any stale same-topic channel before subscribing again
    // closes that window.
    let cancelled = false;
    const supabase = createClient();
    let channel: ReturnType<typeof supabase.channel> | null = null;

    async function loadUnreadCount(column: string, value: string) {
      const { count } = await supabase
        .from("notifications")
        .select("id", { count: "exact", head: true })
        .eq(column, value)
        .eq("is_read", false);
      if (!cancelled) setUnreadCount(count ?? 0);
    }

    void (async () => {
      const scope = await resolveScope(supabase);
      if (!scope || cancelled) return;

      await loadUnreadCount(scope.column, scope.value);
      if (cancelled) return;

      // Topic carries the column too, so a user who is both a customer and
      // vendor staff runs two distinct channels rather than one that the
      // dedupe-by-topic in supabase.channel() would collapse.
      const topic = `notifications:${scope.column}:${scope.value}`;
      const stale = supabase.getChannels().find((c) => c.topic === `realtime:${topic}`);
      if (stale) await supabase.removeChannel(stale);
      if (cancelled) return;

      channel = supabase
        .channel(topic)
        .on(
          "postgres_changes",
          {
            event: "*",
            schema: "public",
            table: "notifications",
            filter: `${scope.column}=eq.${scope.value}`,
          },
          () => void loadUnreadCount(scope.column, scope.value),
        )
        .subscribe();
    })();

    return () => {
      cancelled = true;
      if (channel) void supabase.removeChannel(channel);
    };
  }, [resolveScope]);

  useEffect(() => {
    if (!isOpen) return;
    function onClickOutside(event: MouseEvent) {
      if (containerRef.current && !containerRef.current.contains(event.target as Node)) {
        setIsOpen(false);
      }
    }
    document.addEventListener("mousedown", onClickOutside);
    return () => document.removeEventListener("mousedown", onClickOutside);
  }, [isOpen]);

  async function handleOpen() {
    setIsOpen((open) => !open);
    if (items.length > 0 || isOpen) return;

    const supabase = createClient();
    const scope = await resolveScope(supabase);
    if (!scope) return;

    const { data } = await supabase
      .from("notifications")
      .select("id, title, body, is_read, created_at")
      .eq(scope.column, scope.value)
      .order("created_at", { ascending: false })
      .limit(15);
    setItems(data ?? []);
  }

  async function handleMarkAllRead() {
    const supabase = createClient();
    const scope = await resolveScope(supabase);
    if (!scope) return;

    await supabase
      .from("notifications")
      .update({ is_read: true })
      .eq(scope.column, scope.value)
      .eq("is_read", false);
    setItems((prev) => prev.map((n) => ({ ...n, is_read: true })));
    setUnreadCount(0);
  }

  return (
    <div className="relative" ref={containerRef}>
      <button
        type="button"
        onClick={() => void handleOpen()}
        className={buttonClassName}
        aria-label={`Notifications${unreadCount > 0 ? `, ${unreadCount} unread` : ""}`}
        aria-expanded={isOpen}
      >
        <Bell className={iconClassName} />
        {unreadCount > 0 && (
          <span className="absolute right-1.5 top-1.5 size-2 rounded-full bg-[#B61913]" />
        )}
      </button>

      {isOpen && (
        <div className="absolute right-0 top-full z-50 mt-2 max-h-[70vh] w-80 overflow-y-auto rounded-2xl border border-[#E4BEB8] bg-white shadow-lg">
          <div className="flex items-center justify-between border-b border-[#E4BEB8] px-4 py-3">
            <span className="font-sora text-sm font-semibold text-[#1C1B1B]">Notifications</span>
            {unreadCount > 0 && (
              <button
                type="button"
                onClick={() => void handleMarkAllRead()}
                className="flex items-center gap-1 font-inter text-xs font-medium text-[#B61913] hover:underline"
              >
                <CheckCheck className="size-3.5" />
                Mark all read
              </button>
            )}
          </div>

          {webPush.status === "not_subscribed" && (
            <button
              type="button"
              onClick={() => void webPush.subscribe()}
              className="flex w-full items-center gap-2 border-b border-[#E4BEB8] bg-[#FFF6F5] px-4 py-2.5 text-left font-inter text-xs font-medium text-[#B61913] hover:bg-[#FFECEA]"
            >
              <BellRing className="size-3.5 shrink-0" />
              Enable push notifications for order updates
            </button>
          )}

          {webPush.status === "subscribed" && (
            <button
              type="button"
              onClick={() => void webPush.unsubscribe()}
              className="flex w-full items-center gap-2 border-b border-[#E4BEB8] px-4 py-2.5 text-left font-inter text-xs font-medium text-[#5B403C] hover:bg-[#F6F3F2]"
            >
              <BellRing className="size-3.5 shrink-0 text-[#176A22]" />
              Push notifications on
              <span className="ml-auto text-[11px] font-normal underline">Turn off</span>
            </button>
          )}

          {items.length === 0 ? (
            <p className="px-4 py-8 text-center font-inter text-sm text-[#5B403C]">{emptyMessage}</p>
          ) : (
            <ul>
              {items.map((n) => (
                <li key={n.id} className={`border-b border-[#F0EDED] px-4 py-3 last:border-b-0 ${n.is_read ? "" : "bg-[#FFF6F5]"}`}>
                  <div className="flex items-start gap-2">
                    {!n.is_read && <span className="mt-1.5 size-1.5 shrink-0 rounded-full bg-[#B61913]" />}
                    <div className={n.is_read ? "ml-3.5" : ""}>
                      <p className="font-inter text-sm font-semibold text-[#1C1B1B]">{n.title}</p>
                      <p className="mt-0.5 font-inter text-xs text-[#5B403C]">{n.body}</p>
                      <p className="mt-1 font-inter text-[11px] text-[#5B403C]/70">{timeAgo(n.created_at)}</p>
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>
      )}
    </div>
  );
}
